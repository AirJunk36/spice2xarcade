    constexpr uint32_t ticker_mask(char ch) {
        switch (ch) {
            case 'B': return 0x94f3;
            case 'D': return 0x887c;
            case 'E': return 0x88f3;
            case '!': return 0x0622;
            case 'Y': return 0x2500;
            case '?': return 0x0423;
            case '.': return 0x0020;
            default: return ch >= ' ' && ch <= '~' ? ascii_segments[ch - ' '] : 0;
        }
    }

    inline void draw_ticker(const std::array<char, 10> &ticker, float scale) {
        const auto start = ImGui::GetCursorScreenPos();
        const float unit = (200.f / 884.f) * scale;
        auto *draw = ImGui::GetWindowDrawList();
        for (size_t digit = 0; digit < 9; ++digit) {
            const char ch = ticker[digit];
            const auto mask = ticker_mask(ch == 'm' ? '.' : ch == 'q' ? '\'' : ch);
            for (size_t i = 0; i < std::size(segment_shapes); ++i) {
                const auto &shape = segment_shapes[i];
                ImVec2 points[6];
                for (int v = 0; v < shape.vertices; ++v) {
                    const auto p = shape.points[v];
                    points[v] = {start.x + digit * 140.f * scale + (p.x + 0.1f * p.y) * 0.9f * unit,
                        start.y + (884.f - p.y) * unit};
                }
                draw->AddConvexPolyFilled(points, shape.vertices, (mask & (1u << i))
                    ? IM_COL32(204, 0, 0, 255) : IM_COL32(38, 38, 38, 204));
            }
        }
    }
